def render_report(path: str, fps: float | None = None, bands: bool = True,
                  sections: bool = True) -> str:
    """Analyze ``path`` and return a complete self-contained HTML string."""
    result = analyze(path, fps=fps, bands=bands, sections=sections)
    payload = result.to_dict()
    title = Path(path).name
    html = _TEMPLATE
    html = html.replace("__PAYLOAD__", json.dumps(payload))
    html = html.replace("__TITLE__", title)
    html = html.replace("__VERSION__", __version__)
    return html


def write_report(path: str, out: str, fps: float | None = None) -> str:
    html = render_report(path, fps=fps)
    with open(out, "w", encoding="utf-8") as f:
        f.write(html)
    return out
