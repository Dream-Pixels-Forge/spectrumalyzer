"""Remotion export — frame-native JSON + a ready-to-import React hook.

Remotion timelines are frame-indexed, so all times are pre-converted:
beat #n lands on ``beatsInFrames[n]`` with zero runtime math in the video.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from spectrumalyzer.model import AnalysisResult, time_to_frame


def _require_fps(result: AnalysisResult) -> float:
    if not result.fps:
        raise ValueError("Remotion export needs fps — pass --fps (or fps= to analyze)")
    return result.fps


def render(result: AnalysisResult) -> str:
    fps = _require_fps(result)
    data: dict[str, Any] = {
        "bpm": round(result.bpm, 2),
        "bpmConfidence": round(result.bpm_confidence, 3),
        "fps": int(fps) if fps == int(fps) else fps,
        "durationInSeconds": round(result.duration, 3),
        "durationInFrames": time_to_frame(result.duration, fps),
        "beatPeriodInSeconds": round(result.beat_period, 5),
        "beatPeriodInFrames": round(60.0 / result.bpm * fps) if result.bpm else 0,
        "beatsInFrames": [time_to_frame(b.time, fps) for b in result.beat_grid],
        "beatStrengths": [round(b.strength, 3) for b in result.beat_grid],
        "onsetsInFrames": [time_to_frame(o.time, fps) for o in result.onsets],
        "sections": [
            {
                "startFrame": time_to_frame(s.start, fps),
                "endFrame": time_to_frame(s.end, fps),
                "label": s.label,
                "energy": round(s.energy, 3),
            }
            for s in result.sections
        ],
    }
    rows = result.band_rows_at_fps()
    if rows is not None:
        data["bandsByFrame"] = rows
        data["bandNames"] = ["sub", "bass", "lowMid", "mid", "highMid", "treble"]
    return json.dumps(data, indent=2)


def extras(result: AnalysisResult, base: str = "song") -> dict[str, str]:
    """Companion React hook: useBeats() for beat-synced components.

    ``base`` is the output base path (no extension); filenames derive from it.
    """
    data_name = Path(base).name + ".remotion.json"
    hook = f"""import {{useCallback, useMemo}} from 'react';
import {{useVideoConfig, interpolate, spring}} from 'remotion';
import beats from './{data_name}';

/**
 * Beat-sync helpers generated by spectrumalyzer.
 * Data: {len(result.beat_grid)} beats, {result.bpm} BPM at {int(result.fps or fps_of(result))} fps.
 */
export const BEATS: number[] = beats.beatsInFrames;
export const BPM: number = beats.bpm;
export const DURATION_IN_FRAMES: number = beats.durationInFrames;

/** All beat data for the current composition. */
export const useBeats = () => beats;

/** Index of the most recent beat at the current frame. */
export const useBeatIndex = (): number => {{
  const {{frame}} = useVideoConfig();
  let idx = -1;
  for (let i = 0; i < BEATS.length; i++) {{
    if (BEATS[i] <= frame) idx = i;
    else break;
  }}
  return idx;
}};

/** 0 -> 1 progress within the current beat interval (clamped at 1). */
export const useBeatProgress = (): number => {{
  const {{frame}} = useVideoConfig();
  const idx = useBeatIndex();
  if (idx < 0) return 0;
  const start = BEATS[idx];
  const end = idx + 1 < BEATS.length ? BEATS[idx + 1] : DURATION_IN_FRAMES;
  return Math.min(1, (frame - start) / Math.max(1, end - start));
}};

/** True when frame is within `window` frames after a beat — drive pulses with it. */
export const useIsOnBeat = (window = 2): boolean => {{
  const {{frame}} = useVideoConfig();
  return BEATS.some((b) => frame >= b && frame <= b + window);
}};

/**
 * Springy pop that retriggers on every beat:
 *   const scale = useBeatPop();   // 1.0 .. ~1.15 per beat
 */
export const useBeatPop = (amount = 0.15): number => {{
  const {{frame, fps}} = useVideoConfig();
  const idx = useBeatIndex();
  if (idx < 0) return 1;
  return 1 + amount * spring({{
    frame: frame - BEATS[idx],
    fps,
    config: {{damping: 12, stiffness: 200, mass: 0.5}},
  }});
}};
"""
    return {".useBeats.ts": hook}


def fps_of(result: AnalysisResult) -> float:
    return result.fps or 30.0
